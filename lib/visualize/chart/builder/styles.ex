    @doc """
    Returns the builder's stylesheet as a binary (spec/14 §18.13).

    Every rule is scoped under `.vis-builder`, and every colour and metric is a custom
    property declared there. Write it beside the hooks where an asset pipeline will find it,
    or let the builder render it — `styles/1` is what it renders.

        iex> css = Visualize.Chart.Builder.Styles.css()
        iex> String.contains?(css, "--vis-builder-accent")
        true
    """
    @spec css() :: binary()
    def css, do: @stylesheet

    @doc """
    Returns the path where the stylesheet should be installed, beside the hooks.

        iex> Visualize.Chart.Builder.Styles.default_path()
        "assets/css/visualize_builder.css"
    """
    @spec default_path() :: binary()
    def default_path, do: "assets/css/visualize_builder.css"

    @doc """
    Writes the stylesheet to `default_path/0`, as `Visualize.Hooks.install!/0` writes the
    hooks. A host that does this renders the builder with `styles={false}`.
    """
    @spec install!() :: {:ok, binary()}
    def install! do
      path = default_path()
      File.mkdir_p!(Path.dirname(path))
      File.write!(path, css())
      {:ok, path}
    end

    @doc """
    Renders the stylesheet in a `<style>` element (spec/10 §15.3).

    The builder emits this at its own root, so a host with no asset pipeline gets a legible
    builder from the `<.live_component>` call alone (D-94).
    """
    def styles(assigns) do
      assigns = assign_new(assigns, :nonce, fn -> nil end)

      # HEEx does not interpolate `{...}` inside a `<style>` or `<script>` body — that text is
      # raw by design — so the stylesheet goes in through `<%= %>`.
      ~H"""
      <style nonce={@nonce}><%= Phoenix.HTML.raw(css()) %></style>
      """
    end
  end
