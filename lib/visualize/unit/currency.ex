  @minor Map.new(@table, fn {code, minor, _name} -> {code, minor} end)

  @doc false
  # Whether a string is a code of the table.
  def known?(code), do: is_map_key(@minor, code)

  @doc false
  # A code's minor units, `nil` for none; raises for a code not in the table.
  def minor_units(code) do
    case Map.fetch(@minor, code) do
      {:ok, minor} -> minor
      :error -> raise ArgumentError, "not an ISO 4217 code visualize knows: #{inspect(code)}"
    end
  end

  @doc false
  # Every code and its minor units and name, in the table's order.
  def table, do: @table
