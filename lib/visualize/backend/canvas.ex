defmodule Visualize.Backend.Canvas do
  @moduledoc """
  Canvas 2D API rendering backend.

  Generates JavaScript code that draws to a Canvas 2D context.
  Can output either raw JS commands, JSON structure for client-side
  rendering, or a list of command tuples.

  ## Output Formats

    * `:js` - JavaScript code string (default)
    * `:json` - JSON array of command objects
    * `:commands` - Elixir list of command tuples
    * `:binary` - Compact binary format (requires Nx, ~80% smaller than JSON)
    * `:binary_base64` - Binary format encoded as base64 string

  ## Examples

      element = IR.Element.path(path, %{stroke: "blue", fill: :none})

      # JavaScript output
      Visualize.Render.to_canvas_string(element, format: :js)
      # => "ctx.beginPath();\\nctx.moveTo(0, 0);\\n..."

      # JSON output
      Visualize.Render.to_canvas_string(element, format: :json)
      # => "[{\\"cmd\\":\\"beginPath\\",\\"args\\":[]}...]"

  """

  @behaviour Visualize.Backend

  alias Visualize.IR.{Element, Path, Transform}

  @type output_format :: :js | :json | :commands | :binary | :binary_base64

  alias Visualize.Backend.CanvasBinary

  # ============================================================
  # Backend Callbacks
  # ============================================================

  @impl true
  @spec path_data(Path.t()) :: [tuple()]
  def path_data(%Path{commands: commands}) do
    Enum.flat_map(commands, &command_to_canvas/1)
  end

  @impl true
  @spec render_path(Path.t(), keyword()) :: iolist() | [tuple()]
  def render_path(%Path{} = path, opts \\ []) do
    format = Keyword.get(opts, :format, :js)
    commands = path_data(path)
    style = Keyword.get(opts, :style, %{})

    full_commands =
      style_setup_commands(style) ++
        [{:beginPath, []}] ++
        commands ++
        style_apply_commands(style)

    format_output(full_commands, format)
  end

  @impl true
  @spec render_element(Element.t(), keyword()) :: iolist() | [tuple()] | binary()
  def render_element(%Element{} = element, opts \\ []) do
    format = Keyword.get(opts, :format, :js)

    case format do
      :binary ->
        CanvasBinary.encode_element!(element)

      :binary_base64 ->
        element
        |> CanvasBinary.encode_element!()
        |> CanvasBinary.to_base64()

      _ ->
        commands = element_to_commands(element)
        format_output(commands, format)
    end
  end

  @impl true
  @spec render_scene([Element.t()], keyword()) :: iolist() | [tuple()]
  def render_scene(elements, opts \\ []) do
    format = Keyword.get(opts, :format, :js)

    all_commands = Enum.flat_map(elements, &element_to_commands/1)

    case format do
      :js ->
        [
          "// Generated by Visualize Canvas Backend\n",
          "(function(ctx) {\n",
          commands_to_js(all_commands),
          "})(context);\n"
        ]

      :json ->
        commands_to_json(all_commands)

      :commands ->
        all_commands
    end
  end

  @impl true
  @spec wrap_root(iolist(), keyword()) :: iolist()
  def wrap_root(content, opts) do
    width = Keyword.get(opts, :width, 800)
    height = Keyword.get(opts, :height, 600)
    canvas_id = Keyword.get(opts, :canvas_id, "visualize-canvas")

    [
      "<canvas id=\"",
      canvas_id,
      "\" width=\"",
      to_string(width),
      "\" height=\"",
      to_string(height),
      "\"></canvas>\n",
      "<script>\n",
      "(function() {\n",
      "  var canvas = document.getElementById('",
      canvas_id,
      "');\n",
      "  var ctx = canvas.getContext('2d');\n",
      content,
      "})();\n",
      "</script>\n"
    ]
  end

  # ============================================================
  # Element to Commands Conversion
  # ============================================================

  defp element_to_commands(%Element{type: :path, path: path, style: style, transform: transform}) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    path_cmds = path_data(path)

    setup ++ [{:beginPath, []}] ++ path_cmds ++ style_apply_commands(style)
  end

  defp element_to_commands(%Element{
         type: :rect,
         attrs: attrs,
         style: style,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{x: x, y: y, width: w, height: h} = attrs

    setup ++
      [{:beginPath, []}, {:rect, [x, y, w, h]}] ++
      style_apply_commands(style)
  end

  defp element_to_commands(%Element{
         type: :circle,
         attrs: attrs,
         style: style,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{cx: cx, cy: cy, r: r} = attrs

    setup ++
      [{:beginPath, []}, {:arc, [cx, cy, r, 0, 2 * :math.pi()]}] ++
      style_apply_commands(style)
  end

  defp element_to_commands(%Element{
         type: :ellipse,
         attrs: attrs,
         style: style,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{cx: cx, cy: cy, rx: rx, ry: ry} = attrs

    setup ++
      [{:beginPath, []}, {:ellipse, [cx, cy, rx, ry, 0, 0, 2 * :math.pi()]}] ++
      style_apply_commands(style)
  end

  defp element_to_commands(%Element{
         type: :line,
         attrs: attrs,
         style: style,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{x1: x1, y1: y1, x2: x2, y2: y2} = attrs

    setup ++
      [
        {:beginPath, []},
        {:moveTo, [x1, y1]},
        {:lineTo, [x2, y2]},
        {:stroke, []}
      ]
  end

  defp element_to_commands(%Element{
         type: :polyline,
         attrs: attrs,
         style: style,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    points = attrs[:points] || []

    path_cmds =
      case points do
        [{x, y} | rest] ->
          [{:moveTo, [x, y]}] ++ Enum.map(rest, fn {px, py} -> {:lineTo, [px, py]} end)

        _ ->
          []
      end

    setup ++ [{:beginPath, []}] ++ path_cmds ++ style_apply_commands(style)
  end

  defp element_to_commands(%Element{
         type: :polygon,
         attrs: attrs,
         style: style,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    points = attrs[:points] || []

    path_cmds =
      case points do
        [{x, y} | rest] ->
          [{:moveTo, [x, y]}] ++
            Enum.map(rest, fn {px, py} -> {:lineTo, [px, py]} end) ++
            [{:closePath, []}]

        _ ->
          []
      end

    setup ++ [{:beginPath, []}] ++ path_cmds ++ style_apply_commands(style)
  end

  defp element_to_commands(%Element{
         type: :text,
         attrs: attrs,
         style: style,
         content: content,
         transform: transform
       }) do
    setup = transform_commands(transform) ++ text_style_commands(style)
    x = attrs[:x] || 0
    y = attrs[:y] || 0

    setup ++ [{:fillText, [content || "", x, y]}]
  end

  defp element_to_commands(%Element{type: :group, children: children, transform: transform}) do
    setup = [{:save, []}] ++ transform_commands(transform)
    child_cmds = Enum.flat_map(children, &element_to_commands/1)
    teardown = [{:restore, []}]

    setup ++ child_cmds ++ teardown
  end

  defp element_to_commands(%Element{type: :root, children: children}) do
    Enum.flat_map(children, &element_to_commands/1)
  end

  # Skip defs, gradients, clip paths (not directly renderable to Canvas)
  defp element_to_commands(%Element{type: type})
       when type in [:defs, :clip_path, :linear_gradient, :radial_gradient, :stop] do
    []
  end

  defp element_to_commands(%Element{type: :image, attrs: attrs, transform: transform}) do
    setup = transform_commands(transform)
    %{href: href, x: x, y: y, width: w, height: h} = attrs

    # Image loading is async in Canvas, output a placeholder
    setup ++ [{:drawImage, [href, x, y, w, h]}]
  end

  # ============================================================
  # Path Command Conversion
  # ============================================================

  defp command_to_canvas({:M, x, y}), do: [{:moveTo, [x, y]}]
  defp command_to_canvas({:m, dx, dy}), do: [{:moveTo_rel, [dx, dy]}]
  defp command_to_canvas({:L, x, y}), do: [{:lineTo, [x, y]}]
  defp command_to_canvas({:l, dx, dy}), do: [{:lineTo_rel, [dx, dy]}]
  defp command_to_canvas({:H, x}), do: [{:lineTo_h, [x]}]
  defp command_to_canvas({:h, dx}), do: [{:lineTo_h_rel, [dx]}]
  defp command_to_canvas({:V, y}), do: [{:lineTo_v, [y]}]
  defp command_to_canvas({:v, dy}), do: [{:lineTo_v_rel, [dy]}]

  defp command_to_canvas({:C, x1, y1, x2, y2, x, y}),
    do: [{:bezierCurveTo, [x1, y1, x2, y2, x, y]}]

  defp command_to_canvas({:c, dx1, dy1, dx2, dy2, dx, dy}),
    do: [{:bezierCurveTo_rel, [dx1, dy1, dx2, dy2, dx, dy]}]

  defp command_to_canvas({:S, x2, y2, x, y}), do: [{:bezierCurveTo_smooth, [x2, y2, x, y]}]

  defp command_to_canvas({:s, dx2, dy2, dx, dy}),
    do: [{:bezierCurveTo_smooth_rel, [dx2, dy2, dx, dy]}]

  defp command_to_canvas({:Q, x1, y1, x, y}), do: [{:quadraticCurveTo, [x1, y1, x, y]}]

  defp command_to_canvas({:q, dx1, dy1, dx, dy}),
    do: [{:quadraticCurveTo_rel, [dx1, dy1, dx, dy]}]

  defp command_to_canvas({:T, x, y}), do: [{:quadraticCurveTo_smooth, [x, y]}]
  defp command_to_canvas({:t, dx, dy}), do: [{:quadraticCurveTo_smooth_rel, [dx, dy]}]

  defp command_to_canvas({:A, rx, ry, rotation, large_arc, sweep, x, y}),
    do: [{:arcSvg, [rx, ry, rotation, large_arc, sweep, x, y]}]

  defp command_to_canvas({:a, rx, ry, rotation, large_arc, sweep, dx, dy}),
    do: [{:arcSvg_rel, [rx, ry, rotation, large_arc, sweep, dx, dy]}]

  defp command_to_canvas(:Z), do: [{:closePath, []}]

  # ============================================================
  # Transform Commands
  # ============================================================

  defp transform_commands(nil), do: []
  defp transform_commands(%Transform{operations: []}), do: []

  defp transform_commands(%Transform{operations: ops}) do
    Enum.map(ops, fn
      {:translate, x, y} -> {:translate, [x, y]}
      {:rotate, angle} -> {:rotate, [angle * :math.pi() / 180]}
      {:rotate, angle, cx, cy} -> {:rotate_around, [angle * :math.pi() / 180, cx, cy]}
      {:scale, sx, sy} -> {:scale, [sx, sy]}
      {:skew_x, angle} -> {:transform, [1, 0, :math.tan(angle * :math.pi() / 180), 1, 0, 0]}
      {:skew_y, angle} -> {:transform, [1, :math.tan(angle * :math.pi() / 180), 0, 1, 0, 0]}
      {:matrix, a, b, c, d, e, f} -> {:transform, [a, b, c, d, e, f]}
    end)
  end

  # ============================================================
  # Style Commands
  # ============================================================

  defp style_setup_commands(style) when map_size(style) == 0, do: []

  defp style_setup_commands(style) do
    cmds = []

    cmds =
      case style[:fill] do
        nil -> cmds
        :none -> cmds
        :current_color -> cmds ++ [{:set_fillStyle, ["currentColor"]}]
        color -> cmds ++ [{:set_fillStyle, [to_string(color)]}]
      end

    cmds =
      case style[:stroke] do
        nil -> cmds
        :none -> cmds
        :current_color -> cmds ++ [{:set_strokeStyle, ["currentColor"]}]
        color -> cmds ++ [{:set_strokeStyle, [to_string(color)]}]
      end

    cmds =
      if style[:stroke_width],
        do: cmds ++ [{:set_lineWidth, [style[:stroke_width]]}],
        else: cmds

    cmds =
      case style[:stroke_linecap] do
        nil -> cmds
        cap -> cmds ++ [{:set_lineCap, [to_string(cap)]}]
      end

    cmds =
      case style[:stroke_linejoin] do
        nil -> cmds
        join -> cmds ++ [{:set_lineJoin, [to_string(join)]}]
      end

    cmds =
      if style[:opacity],
        do: cmds ++ [{:set_globalAlpha, [style[:opacity]]}],
        else: cmds

    cmds
  end

  defp style_apply_commands(style) when map_size(style) == 0, do: []

  defp style_apply_commands(style) do
    cmds = []

    cmds =
      case style[:fill] do
        nil -> cmds
        :none -> cmds
        _ -> cmds ++ [{:fill, []}]
      end

    cmds =
      case style[:stroke] do
        nil -> cmds
        :none -> cmds
        _ -> cmds ++ [{:stroke, []}]
      end

    cmds
  end

  defp text_style_commands(style) do
    cmds = []

    cmds =
      if style[:font_size] || style[:font_family] do
        size = style[:font_size] || 10
        family = style[:font_family] || "sans-serif"
        cmds ++ [{:set_font, ["#{size}px #{family}"]}]
      else
        cmds
      end

    cmds =
      case style[:text_anchor] do
        :start -> cmds ++ [{:set_textAlign, ["left"]}]
        :middle -> cmds ++ [{:set_textAlign, ["center"]}]
        :end -> cmds ++ [{:set_textAlign, ["right"]}]
        _ -> cmds
      end

    cmds =
      case style[:fill] do
        nil -> cmds
        :none -> cmds
        :current_color -> cmds ++ [{:set_fillStyle, ["currentColor"]}]
        color -> cmds ++ [{:set_fillStyle, [to_string(color)]}]
      end

    cmds
  end

  # ============================================================
  # Output Formatting
  # ============================================================

  defp format_output(commands, :commands), do: commands
  defp format_output(commands, :js), do: commands_to_js(commands)
  defp format_output(commands, :json), do: commands_to_json(commands)

  defp commands_to_js(commands) do
    commands
    |> Enum.map(&command_to_js_line/1)
    |> Enum.intersperse("\n")
  end

  defp command_to_js_line({:set_fillStyle, [color]}), do: ["ctx.fillStyle = '", color, "';"]
  defp command_to_js_line({:set_strokeStyle, [color]}), do: ["ctx.strokeStyle = '", color, "';"]
  defp command_to_js_line({:set_lineWidth, [w]}), do: ["ctx.lineWidth = ", format_num(w), ";"]
  defp command_to_js_line({:set_lineCap, [cap]}), do: ["ctx.lineCap = '", cap, "';"]
  defp command_to_js_line({:set_lineJoin, [join]}), do: ["ctx.lineJoin = '", join, "';"]
  defp command_to_js_line({:set_globalAlpha, [a]}), do: ["ctx.globalAlpha = ", format_num(a), ";"]
  defp command_to_js_line({:set_font, [font]}), do: ["ctx.font = '", font, "';"]
  defp command_to_js_line({:set_textAlign, [align]}), do: ["ctx.textAlign = '", align, "';"]
  defp command_to_js_line({:beginPath, []}), do: "ctx.beginPath();"
  defp command_to_js_line({:closePath, []}), do: "ctx.closePath();"

  defp command_to_js_line({:moveTo, [x, y]}),
    do: ["ctx.moveTo(", format_num(x), ", ", format_num(y), ");"]

  defp command_to_js_line({:lineTo, [x, y]}),
    do: ["ctx.lineTo(", format_num(x), ", ", format_num(y), ");"]

  defp command_to_js_line({:bezierCurveTo, [x1, y1, x2, y2, x, y]}) do
    [
      "ctx.bezierCurveTo(",
      format_num(x1),
      ", ",
      format_num(y1),
      ", ",
      format_num(x2),
      ", ",
      format_num(y2),
      ", ",
      format_num(x),
      ", ",
      format_num(y),
      ");"
    ]
  end

  defp command_to_js_line({:quadraticCurveTo, [x1, y1, x, y]}) do
    [
      "ctx.quadraticCurveTo(",
      format_num(x1),
      ", ",
      format_num(y1),
      ", ",
      format_num(x),
      ", ",
      format_num(y),
      ");"
    ]
  end

  defp command_to_js_line({:arc, args}) do
    formatted = Enum.map(args, &format_num/1) |> Enum.intersperse(", ")
    ["ctx.arc(", formatted, ");"]
  end

  defp command_to_js_line({:ellipse, args}) do
    formatted = Enum.map(args, &format_num/1) |> Enum.intersperse(", ")
    ["ctx.ellipse(", formatted, ");"]
  end

  defp command_to_js_line({:rect, [x, y, w, h]}) do
    [
      "ctx.rect(",
      format_num(x),
      ", ",
      format_num(y),
      ", ",
      format_num(w),
      ", ",
      format_num(h),
      ");"
    ]
  end

  defp command_to_js_line({:fill, []}), do: "ctx.fill();"
  defp command_to_js_line({:stroke, []}), do: "ctx.stroke();"
  defp command_to_js_line({:save, []}), do: "ctx.save();"
  defp command_to_js_line({:restore, []}), do: "ctx.restore();"

  defp command_to_js_line({:translate, [x, y]}),
    do: ["ctx.translate(", format_num(x), ", ", format_num(y), ");"]

  defp command_to_js_line({:rotate, [angle]}), do: ["ctx.rotate(", format_num(angle), ");"]

  defp command_to_js_line({:rotate_around, [angle, cx, cy]}) do
    [
      "ctx.translate(",
      format_num(cx),
      ", ",
      format_num(cy),
      "); ctx.rotate(",
      format_num(angle),
      "); ctx.translate(",
      format_num(-cx),
      ", ",
      format_num(-cy),
      ");"
    ]
  end

  defp command_to_js_line({:scale, [sx, sy]}),
    do: ["ctx.scale(", format_num(sx), ", ", format_num(sy), ");"]

  defp command_to_js_line({:transform, [a, b, c, d, e, f]}) do
    [
      "ctx.transform(",
      format_num(a),
      ", ",
      format_num(b),
      ", ",
      format_num(c),
      ", ",
      format_num(d),
      ", ",
      format_num(e),
      ", ",
      format_num(f),
      ");"
    ]
  end

  defp command_to_js_line({:fillText, [text, x, y]}) do
    ["ctx.fillText('", escape_js(text || ""), "', ", format_num(x), ", ", format_num(y), ");"]
  end

  defp command_to_js_line({:drawImage, [href, x, y, w, h]}) do
    [
      "// Image: ",
      href,
      "\n",
      "// Note: Image loading requires async handling\n",
      "// ctx.drawImage(img, ",
      format_num(x),
      ", ",
      format_num(y),
      ", ",
      format_num(w),
      ", ",
      format_num(h),
      ");"
    ]
  end

  # SVG arc commands need conversion helper
  defp command_to_js_line({:arcSvg, [rx, ry, rotation, large_arc, sweep, x, y]}) do
    [
      "// SVG Arc: arcSvgToCanvas(ctx, ",
      Enum.map([rx, ry, rotation, large_arc, sweep, x, y], &format_num/1)
      |> Enum.intersperse(", "),
      ");"
    ]
  end

  # Handle relative and smooth commands with comments
  defp command_to_js_line({cmd, args}) when is_atom(cmd) do
    cmd_str = Atom.to_string(cmd)
    args_str = Enum.map(args, &format_num/1) |> Enum.intersperse(", ")
    ["// ", cmd_str, "(", args_str, ");"]
  end

  defp commands_to_json(commands) do
    encoded =
      commands
      |> Enum.map(fn {cmd, args} ->
        %{cmd: Atom.to_string(cmd), args: args}
      end)

    # Simple JSON encoding without external deps
    ["[", encode_json_array(encoded), "]"]
  end

  defp encode_json_array([]), do: ""

  defp encode_json_array(items) do
    items
    |> Enum.map(&encode_json_object/1)
    |> Enum.intersperse(",")
  end

  defp encode_json_object(%{cmd: cmd, args: args}) do
    args_json =
      args
      |> Enum.map(&encode_json_value/1)
      |> Enum.intersperse(",")

    ["{\"cmd\":\"", cmd, "\",\"args\":[", args_json, "]}"]
  end

  defp encode_json_value(v) when is_binary(v), do: ["\"", escape_json_string(v), "\""]
  defp encode_json_value(v) when is_number(v), do: format_num(v)
  defp encode_json_value(v) when is_atom(v), do: ["\"", Atom.to_string(v), "\""]
  defp encode_json_value(v), do: ["\"", to_string(v), "\""]

  defp escape_json_string(str) do
    str
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> String.replace("\n", "\\n")
    |> String.replace("\r", "\\r")
    |> String.replace("\t", "\\t")
  end

  defp escape_js(str) do
    str
    |> String.replace("\\", "\\\\")
    |> String.replace("'", "\\'")
    |> String.replace("\n", "\\n")
  end

  defp format_num(n) when is_integer(n), do: Integer.to_string(n)

  defp format_num(n) when is_float(n) do
    n
    |> Float.round(4)
    |> Float.to_string()
    |> String.trim_trailing("0")
    |> String.trim_trailing(".")
  end

  defp format_num(n), do: to_string(n)
end
