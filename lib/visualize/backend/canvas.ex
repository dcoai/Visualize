defmodule Visualize.Backend.Canvas do
  @moduledoc """
  Canvas 2D API rendering backend.

  Generates JavaScript code that draws to a Canvas 2D context.
  Can output either raw JS commands, JSON structure for client-side
  rendering, or a list of command tuples.

  ## Output Formats

    * `:js` - JavaScript code string (default)
    * `:json` - JSON array of command objects
    * `:commands` - Elixir list of command tuples
    * `:binary` - Compact binary format (requires Nx, ~80% smaller than JSON)
    * `:binary_base64` - Binary format encoded as base64 string

  Every path command is executable in every format: relative and single-axis commands
  are resolved on the server, smooth curves are expanded, and arcs become `ellipse`
  calls (`Visualize.IR.Path.absolute/1`, `Visualize.Backend.Canvas.Arc`; D-37).

  ## Examples

      element = IR.Element.path(path, %{stroke: "blue", fill: :none})

      # JavaScript output
      Visualize.Render.to_canvas_string(element, format: :js)
      # => "ctx.beginPath();\\nctx.moveTo(0, 0);\\n..."

      # JSON output
      Visualize.Render.to_canvas_string(element, format: :json)
      # => "[{\\"cmd\\":\\"beginPath\\",\\"args\\":[]}...]"

  """

  @behaviour Visualize.Backend

  alias Visualize.Backend.Canvas.{Arc, Output}
  alias Visualize.Backend.CanvasBinary
  alias Visualize.IR.{Element, Motion, Paint, Path, Transform}

  @type output_format :: :js | :json | :commands | :binary | :binary_base64

  # ============================================================
  # Backend Callbacks
  # ============================================================

  # Every IR path command becomes an executable Canvas call: the path is normalized to
  # absolute `M L C Q A Z` first (`Visualize.IR.Path.absolute/1`) and an arc is converted
  # to an `ellipse` call from the current point (D-37).
  @impl true
  @spec path_data(Path.t()) :: [tuple()]
  def path_data(%Path{} = path) do
    %Path{commands: commands} = Path.absolute(path)

    {canvas, _} =
      Enum.flat_map_reduce(commands, {{0, 0}, {0, 0}}, fn cmd, {cur, start} ->
        command_to_canvas(cmd, cur, start)
      end)

    canvas
  end

  @impl true
  @spec render_path(Path.t(), keyword()) :: iolist() | [tuple()]
  def render_path(%Path{} = path, opts \\ []) do
    format = Keyword.get(opts, :format, :js)
    commands = path_data(path)
    style = Keyword.get(opts, :style, %{})

    full_commands =
      style_setup_commands(style) ++
        [{:beginPath, []}] ++
        commands ++
        style_apply_commands(style, Element.path(path, style))

    Output.format_output(full_commands, format)
  end

  @impl true
  @spec render_element(Element.t(), keyword()) :: iolist() | [tuple()] | binary()
  def render_element(%Element{} = element, opts \\ []) do
    format = Keyword.get(opts, :format, :js)

    case format do
      :binary ->
        CanvasBinary.encode_element!(element)

      :binary_base64 ->
        element
        |> CanvasBinary.encode_element!()
        |> CanvasBinary.to_base64()

      _ ->
        commands = element_to_commands(element, %{})
        Output.format_output(commands, format)
    end
  end

  @impl true
  @spec render_scene([Element.t()], keyword()) :: iolist() | [tuple()] | binary()
  def render_scene(elements, opts \\ []) do
    case Keyword.get(opts, :format, :js) do
      :binary ->
        elements |> Enum.map(&CanvasBinary.encode_element!/1) |> IO.iodata_to_binary()

      :binary_base64 ->
        render_scene(elements, format: :binary) |> CanvasBinary.to_base64()

      format ->
        all_commands = Enum.flat_map(elements, &element_to_commands(&1, %{}))

        case format do
          :js ->
            [
              "// Generated by Visualize Canvas Backend\n",
              "(function(ctx) {\n",
              Output.commands_to_js(all_commands),
              "})(context);\n"
            ]

          :json ->
            Output.commands_to_json(all_commands)

          :commands ->
            all_commands
        end
    end
  end

  # The script as a page fragment: a `<canvas>` and the `<script>` that draws it (spec/09
  # §3.6). `:width`, `:height` and `:canvas_id` size and name the element; with a `:title`
  # the canvas is `role="img"` with the title as `aria-label`, and a `:description` is a
  # `<p id="<canvas_id>-summary">` inside it — its fallback content — that
  # `aria-describedby` names (spec/14 §21.4, D-142): `Visualize.Chart.Summary`'s name and
  # text.
  @impl true
  @spec wrap_root(iolist(), keyword()) :: iolist()
  def wrap_root(content, opts) do
    width = Keyword.get(opts, :width, 800)
    height = Keyword.get(opts, :height, 600)
    canvas_id = Keyword.get(opts, :canvas_id, "visualize-canvas")

    [
      "<canvas id=\"",
      canvas_id,
      "\" width=\"",
      to_string(width),
      "\" height=\"",
      to_string(height),
      "\"",
      named_canvas(canvas_id, Keyword.get(opts, :title), Keyword.get(opts, :description)),
      "</canvas>\n",
      "<script>\n",
      "(function() {\n",
      "  var canvas = document.getElementById('",
      canvas_id,
      "');\n",
      "  var ctx = canvas.getContext('2d');\n",
      content,
      "})();\n",
      "</script>\n"
    ]
  end

  @doc false
  # The rest of a `<canvas>` tag after its size, through its fallback content: `role="img"`
  # named by the title and described by the description's paragraph (spec/14 §21.4);
  # nothing more for a canvas with no title.
  @spec named_canvas(String.t(), String.t() | nil, String.t() | nil) :: iolist()
  def named_canvas(_id, nil, _description), do: [">"]

  def named_canvas(id, title, description) do
    escape = &Visualize.Chart.Summary.Table.escape/1

    described =
      if description, do: [~s( aria-describedby="), escape.(id), ~s(-summary")], else: []

    fallback =
      if description,
        do: [~s(<p id="), escape.(id), ~s(-summary">), escape.(description), "</p>"],
        else: []

    [~s( role="img" aria-label="), escape.(title), ~s("), described, ">", fallback]
  end

  # ============================================================
  # Element to Commands Conversion
  # ============================================================

  # An element that names its identity is drawn inside a motion span carrying its style's
  # transition, or a group's above it (spec/09 §3.3.5, D-176); the span holds its commands.
  defp element_to_commands(%Element{attrs: %{"data-vis-id" => id} = attrs} = element, inherited) do
    bare = %{element | attrs: Map.delete(attrs, "data-vis-id")}
    span = Motion.span(id, element, Map.merge(inherited, element.style))
    [{:motion, span}] ++ element_to_commands(bare, inherited) ++ [{:motionEnd, []}]
  end

  # A clipped element (spec/02 §2.1, spec/09 §3.3): the shape's geometry as the clip —
  # alone for inside, under a rectangle of everything with the even-odd rule for
  # outside — around the element's own commands, inside a save/restore pair.
  defp element_to_commands(%Element{clip: %{shape: shape, keep: keep}} = element, inherited) do
    region =
      case keep do
        :inside ->
          geometry(shape) ++ [{:clip, []}]

        :outside ->
          [{:rect, [-100_000, -100_000, 200_000, 200_000]}] ++
            geometry(shape) ++ [{:clip, ["evenodd"]}]
      end

    [{:save, []}, {:beginPath, []}] ++
      region ++ element_to_commands(%{element | clip: nil}, inherited) ++ [{:restore, []}]
  end

  defp element_to_commands(
         %Element{type: :path, path: path, style: style, transform: transform} = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    path_cmds = path_data(path)

    scoped(
      setup,
      [{:beginPath, []}] ++
        path_cmds ++ style_apply_commands(Map.merge(inherited, style), element)
    )
  end

  defp element_to_commands(
         %Element{
           type: :rect,
           attrs: attrs,
           style: style,
           transform: transform
         } = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{x: x, y: y, width: w, height: h} = attrs

    scoped(
      setup,
      [{:beginPath, []}, {:rect, [x, y, w, h]}] ++
        style_apply_commands(Map.merge(inherited, style), element)
    )
  end

  defp element_to_commands(
         %Element{
           type: :circle,
           attrs: attrs,
           style: style,
           transform: transform
         } = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{cx: cx, cy: cy, r: r} = attrs

    scoped(
      setup,
      [{:beginPath, []}, {:arc, [cx, cy, r, 0, 2 * :math.pi()]}] ++
        style_apply_commands(Map.merge(inherited, style), element)
    )
  end

  defp element_to_commands(
         %Element{
           type: :ellipse,
           attrs: attrs,
           style: style,
           transform: transform
         } = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{cx: cx, cy: cy, rx: rx, ry: ry} = attrs

    scoped(
      setup,
      [{:beginPath, []}, {:ellipse, [cx, cy, rx, ry, 0, 0, 2 * :math.pi()]}] ++
        style_apply_commands(Map.merge(inherited, style), element)
    )
  end

  defp element_to_commands(
         %Element{
           type: :line,
           attrs: attrs,
           style: style,
           transform: transform
         } = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    %{x1: x1, y1: y1, x2: x2, y2: y2} = attrs

    scoped(
      setup,
      [{:beginPath, []}, {:moveTo, [x1, y1]}, {:lineTo, [x2, y2]}] ++
        line_stroke(Map.merge(inherited, style), element)
    )
  end

  defp element_to_commands(
         %Element{
           type: :polyline,
           attrs: attrs,
           style: style,
           transform: transform
         } = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    points = attrs[:points] || []

    path_cmds =
      case points do
        [{x, y} | rest] ->
          [{:moveTo, [x, y]}] ++ Enum.map(rest, fn {px, py} -> {:lineTo, [px, py]} end)

        _ ->
          []
      end

    scoped(
      setup,
      [{:beginPath, []}] ++
        path_cmds ++ style_apply_commands(Map.merge(inherited, style), element)
    )
  end

  defp element_to_commands(
         %Element{
           type: :polygon,
           attrs: attrs,
           style: style,
           transform: transform
         } = element,
         inherited
       ) do
    setup = transform_commands(transform) ++ style_setup_commands(style)
    points = attrs[:points] || []

    path_cmds =
      case points do
        [{x, y} | rest] ->
          [{:moveTo, [x, y]}] ++
            Enum.map(rest, fn {px, py} -> {:lineTo, [px, py]} end) ++
            [{:closePath, []}]

        _ ->
          []
      end

    scoped(
      setup,
      [{:beginPath, []}] ++
        path_cmds ++ style_apply_commands(Map.merge(inherited, style), element)
    )
  end

  # A text of several lines (spec/14 §7.1) is one fillText per tspan, each `dy` em below
  # the last at the style's font size (spec/09 §3.3).
  defp element_to_commands(
         %Element{
           type: :text,
           attrs: attrs,
           style: style,
           content: nil,
           children: [_ | _] = lines,
           transform: transform
         },
         inherited
       ) do
    setup = transform_commands(transform) ++ text_style_commands(style)
    x = attrs[:x] || 0
    y = attrs[:y] || 0
    font_size = if is_number(style[:font_size]), do: style[:font_size], else: 10

    {commands, _y} =
      Enum.reduce(lines, {[], y}, fn %Element{attrs: line, content: content}, {acc, at} ->
        at = at + em(line[:dy], font_size)
        {acc ++ [{:fillText, [content || "", line[:x] || x, at]}], at}
      end)

    scoped(setup, alpha(commands, Map.merge(inherited, style), :fill_opacity))
  end

  defp element_to_commands(
         %Element{
           type: :text,
           attrs: attrs,
           style: style,
           content: content,
           transform: transform
         },
         inherited
       ) do
    setup = transform_commands(transform) ++ text_style_commands(style)
    x = attrs[:x] || 0
    y = attrs[:y] || 0

    scoped(
      setup,
      alpha([{:fillText, [content || "", x, y]}], Map.merge(inherited, style), :fill_opacity)
    )
  end

  # A group's style is set after its transform, inside the save/restore pair, so children
  # without a style of their own inherit it through Canvas state (D-37).
  defp element_to_commands(
         %Element{
           type: :group,
           children: children,
           style: style,
           transform: transform
         },
         inherited
       ) do
    setup = [{:save, []}] ++ transform_commands(transform) ++ style_setup_commands(style)
    child_cmds = Enum.flat_map(children, &element_to_commands(&1, Map.merge(inherited, style)))
    teardown = [{:restore, []}]

    setup ++ child_cmds ++ teardown
  end

  defp element_to_commands(%Element{type: :root, children: children}, inherited) do
    Enum.flat_map(children, &element_to_commands(&1, inherited))
  end

  # Skip defs, gradients, clip paths and the accessible name and description: none draws
  defp element_to_commands(%Element{type: type}, _inherited)
       when type in [
              :defs,
              :clip_path,
              :linear_gradient,
              :pattern,
              :radial_gradient,
              :stop,
              :filter,
              :fe_drop_shadow,
              :fe_gaussian_blur,
              :tspan,
              :title,
              :desc,
              :style
            ] do
    []
  end

  defp element_to_commands(%Element{type: :image, attrs: attrs, transform: transform}, _inherited) do
    setup = transform_commands(transform)
    %{href: href, x: x, y: y, width: w, height: h} = attrs
    scoped(setup, [{:drawImage, [href, x, y, w, h]}])
  end

  # A leaf's transform and style are its own (spec/09 §3.3.1, #679, D-179): a leaf whose
  # setup sets either is drawn inside a save/restore pair, so its next sibling draws in its
  # parent's state, as SVG draws it; a leaf that sets neither pays nothing.
  defp scoped([], body), do: body
  defp scoped(setup, body), do: [{:save, []}] ++ setup ++ body ++ [{:restore, []}]

  # A tspan's `dy`: a number as it is, an `em` measure at the font size.
  defp em(nil, _font_size), do: 0
  defp em(n, _font_size) when is_number(n), do: n

  defp em(string, font_size) when is_binary(string) do
    case Float.parse(String.trim_trailing(string, "em")) do
      {n, ""} -> n * font_size
      _other -> 0
    end
  end

  # A shape's geometry alone, for a clip region: no style, no transform.
  defp geometry(%Element{type: :path, path: path}), do: path_data(path)

  defp geometry(%Element{type: :rect, attrs: %{x: x, y: y, width: w, height: h}}),
    do: [{:rect, [x, y, w, h]}]

  defp geometry(%Element{type: :circle, attrs: %{cx: cx, cy: cy, r: r}}),
    do: [{:arc, [cx, cy, r, 0, 2 * :math.pi()]}]

  defp geometry(%Element{type: :ellipse, attrs: %{cx: cx, cy: cy, rx: rx, ry: ry}}),
    do: [{:ellipse, [cx, cy, rx, ry, 0, 0, 2 * :math.pi()]}]

  defp geometry(%Element{type: :polygon, attrs: attrs}) do
    case attrs[:points] || [] do
      [{x, y} | rest] ->
        [{:moveTo, [x, y]}] ++
          Enum.map(rest, fn {px, py} -> {:lineTo, [px, py]} end) ++ [{:closePath, []}]

      _ ->
        []
    end
  end

  # ============================================================
  # Path Command Conversion
  # ============================================================

  # Absolute commands only (after `Path.absolute/1`); the reduce carries the current point
  # and the subpath start, which an arc and a `Z` need.
  defp command_to_canvas({:M, x, y}, _cur, _start), do: {[{:moveTo, [x, y]}], {{x, y}, {x, y}}}
  defp command_to_canvas({:L, x, y}, _cur, start), do: {[{:lineTo, [x, y]}], {{x, y}, start}}

  defp command_to_canvas({:C, x1, y1, x2, y2, x, y}, _cur, start),
    do: {[{:bezierCurveTo, [x1, y1, x2, y2, x, y]}], {{x, y}, start}}

  defp command_to_canvas({:Q, x1, y1, x, y}, _cur, start),
    do: {[{:quadraticCurveTo, [x1, y1, x, y]}], {{x, y}, start}}

  defp command_to_canvas({:A, rx, ry, rot, large, sweep, x, y}, cur, start),
    do: {Arc.to_command(cur, {x, y}, rx, ry, rot, large, sweep), {{x, y}, start}}

  defp command_to_canvas(:Z, _cur, start), do: {[{:closePath, []}], {start, start}}

  # ============================================================
  # Transform Commands
  # ============================================================

  defp transform_commands(nil), do: []
  defp transform_commands(%Transform{operations: []}), do: []

  defp transform_commands(%Transform{operations: ops}) do
    Enum.map(ops, fn
      {:translate, x, y} -> {:translate, [x, y]}
      {:rotate, angle} -> {:rotate, [angle * :math.pi() / 180]}
      {:rotate, angle, cx, cy} -> {:rotate_around, [angle * :math.pi() / 180, cx, cy]}
      {:scale, sx, sy} -> {:scale, [sx, sy]}
      {:skew_x, angle} -> {:transform, [1, 0, :math.tan(angle * :math.pi() / 180), 1, 0, 0]}
      {:skew_y, angle} -> {:transform, [1, :math.tan(angle * :math.pi() / 180), 0, 1, 0, 0]}
      {:matrix, a, b, c, d, e, f} -> {:transform, [a, b, c, d, e, f]}
    end)
  end

  # ============================================================
  # Style Commands
  # ============================================================

  defp style_setup_commands(style) when map_size(style) == 0, do: []

  defp style_setup_commands(style) do
    cmds = []

    cmds =
      case style[:fill] do
        nil -> cmds
        :none -> cmds
        :current_color -> cmds ++ [{:set_fillStyle, ["currentColor"]}]
        %Paint{} -> cmds
        color -> cmds ++ [{:set_fillStyle, [to_string(color)]}]
      end

    cmds =
      case style[:stroke] do
        nil -> cmds
        :none -> cmds
        :current_color -> cmds ++ [{:set_strokeStyle, ["currentColor"]}]
        %Paint{} -> cmds
        color -> cmds ++ [{:set_strokeStyle, [to_string(color)]}]
      end

    # A stroke that keeps its width on screen divides it by the transform's scale when it
    # is set, which only the context knows (spec/09 §3.3.3, spec/14 §3.9).
    cmds =
      case {style[:stroke_width], style[:vector_effect]} do
        {nil, _effect} -> cmds
        {w, :non_scaling_stroke} -> cmds ++ [{:nonScalingLineWidth, [w]}]
        {w, _effect} -> cmds ++ [{:set_lineWidth, [w]}]
      end

    # A blend is the compositing operation; an effect the context's shadow or its filter
    # (spec/09 §3.3.3).
    cmds =
      case style[:blend] do
        blend when blend in [nil, :normal] -> cmds
        blend -> cmds ++ [{:set_globalCompositeOperation, [to_string(blend)]}]
      end

    radius = style[:effect_radius] || 3

    cmds =
      case style[:effect] do
        :shadow ->
          # The offset and the color a shadow gives, else half the radius and black at 0.35
          # (spec/09 §3.3.3, #674).
          [dx, dy] = style[:effect_offset] || [radius / 2, radius / 2]

          color =
            if c = style[:effect_color], do: Paint.canvas_color(c), else: "rgba(0,0,0,0.35)"

          cmds ++
            [
              {:set_shadowColor, [color]},
              {:set_shadowBlur, [radius]},
              {:set_shadowOffsetX, [dx]},
              {:set_shadowOffsetY, [dy]}
            ]

        :blur ->
          cmds ++ [{:set_filter, ["blur(#{radius}px)"]}]

        _none ->
          cmds
      end

    cmds =
      case style[:stroke_linecap] do
        nil -> cmds
        cap -> cmds ++ [{:set_lineCap, [to_string(cap)]}]
      end

    cmds =
      case style[:stroke_linejoin] do
        nil -> cmds
        join -> cmds ++ [{:set_lineJoin, [to_string(join)]}]
      end

    cmds =
      case dash(style[:stroke_dasharray]) do
        nil -> cmds
        pattern -> cmds ++ [{:setLineDash, [pattern]}]
      end

    cmds =
      if style[:opacity],
        do: cmds ++ [{:set_globalAlpha, [style[:opacity]]}],
        else: cmds

    cmds
  end

  defp style_apply_commands(style, _element) when map_size(style) == 0, do: []

  defp style_apply_commands(style, element) do
    alpha(fill_commands(style[:fill], element), style, :fill_opacity) ++
      alpha(stroke_commands(style[:stroke], element), style, :stroke_opacity)
  end

  # A line is stroked where its effective stroke is present, at its own opacity, and never
  # filled (spec/09 §3.3.1, #757).
  defp line_stroke(style, element),
    do: alpha(stroke_commands(style[:stroke], element), style, :stroke_opacity)

  # A paint's own opacity (spec/09 §3.3.3, #675, D-180): its draw at the element's alpha
  # times the paint's, then the element's alpha back for the draw after it. The element's
  # is its effective `opacity`, the one its setup or a group's set; a gradient's stops carry
  # their own alpha, which the context multiplies with this.
  defp alpha([], _style, _key), do: []

  defp alpha(draw, style, key) do
    case Map.get(style, key) do
      a when is_number(a) and a != 1 ->
        o = if is_number(style[:opacity]), do: style[:opacity], else: 1
        [{:set_globalAlpha, [o * a]}] ++ draw ++ [{:set_globalAlpha, [o]}]

      _opaque ->
        draw
    end
  end

  @doc false
  # A dash pattern as the numbers `setLineDash` takes (spec/09 §3.3.3, #675): an SVG
  # `stroke-dasharray` — lengths apart by spaces or commas, or a list — with `none` and an
  # empty one the solid line `[]`; `nil` for one that does not read, which is not drawn.
  @spec dash(term()) :: [number()] | nil
  def dash(nil), do: nil
  def dash(list) when is_list(list), do: if(Enum.all?(list, &is_number/1), do: list)

  def dash(string) when is_binary(string) do
    case String.split(string, ~r/[\s,]+/, trim: true) do
      ["none"] ->
        []

      parts ->
        numbers = Enum.map(parts, &Float.parse/1)
        if Enum.all?(numbers, &match?({_n, ""}, &1)), do: Enum.map(numbers, &elem(&1, 0))
    end
  end

  def dash(_other), do: nil

  defp fill_commands(fill, _element) when fill in [nil, :none], do: []
  defp fill_commands(%Paint{} = paint, element), do: paint_commands(paint, :fill, element)
  defp fill_commands(_color, _element), do: [{:fill, []}]

  defp stroke_commands(stroke, _element) when stroke in [nil, :none], do: []
  defp stroke_commands(%Paint{} = paint, element), do: paint_commands(paint, :stroke, element)
  defp stroke_commands(_color, _element), do: [{:stroke, []}]

  # A paint is drawn over the element's own box, inside a save/restore so the gradient is
  # never state a sibling inherits; a box without area draws nothing, as SVG draws no
  # bounding-box paint on one (spec/09 §3.3.3, D-175).
  # A hatch is laid from the user-space origin, as SVG's `userSpaceOnUse` pattern is, so it
  # needs no box and draws on an element without area (spec/09 §3.3.3, #673).
  defp paint_commands(%Paint{type: :hatch, geometry: g} = paint, op, _element) do
    args = [
      Atom.to_string(op),
      Atom.to_string(g.pattern),
      g.angle,
      g.spacing,
      g.width,
      Paint.canvas_color(paint.color),
      paint.background && Paint.canvas_color(paint.background)
    ]

    [{:save, []}, {:hatchPattern, args}, {op, []}, {:restore, []}]
  end

  defp paint_commands(paint, op, element) do
    case Paint.bounds(element) do
      {_x, _y, w, h} = box when w > 0 and h > 0 ->
        [{:save, []}] ++ gradient_commands(paint, op, box) ++ [{op, []}, {:restore, []}]

      _no_area ->
        []
    end
  end

  # A linear gradient maps exactly into user units; a radial fill is drawn under the box
  # transform, which only the paint sees, and a radial stroke — which that transform would
  # widen unevenly — is the circle of the same area.
  defp gradient_commands(%Paint{type: :linear} = paint, op, box) do
    {x0, y0, x1, y1} = Paint.linear_line(paint, box)
    [{:linearGradient, [Atom.to_string(op), x0, y0, x1, y1, Paint.canvas_stops(paint)]}]
  end

  defp gradient_commands(%Paint{type: :radial, geometry: g} = paint, :fill, {x, y, w, h}) do
    [
      {:transform, [w, 0, 0, h, x, y]},
      {:radialGradient, ["fill", g.cx, g.cy, g.r, Paint.canvas_stops(paint)]}
    ]
  end

  defp gradient_commands(%Paint{type: :radial, geometry: g} = paint, :stroke, {x, y, w, h}) do
    r = g.r * :math.sqrt(w * h)
    [{:radialGradient, ["stroke", x + g.cx * w, y + g.cy * h, r, Paint.canvas_stops(paint)]}]
  end

  defp text_style_commands(style) do
    cmds = []

    cmds =
      if style[:font_size] || style[:font_family] || style[:font_weight] || style[:font_style] do
        size = style[:font_size] || 10
        family = style[:font_family] || "sans-serif"
        # The CSS shorthand: [style] [weight] size family (spec/09 §3).
        font =
          [style[:font_style], style[:font_weight], "#{size}px", family]
          |> Enum.reject(&is_nil/1)
          |> Enum.map_join(" ", &to_string/1)

        cmds ++ [{:set_font, [font]}]
      else
        cmds
      end

    cmds =
      case style[:text_anchor] do
        :start -> cmds ++ [{:set_textAlign, ["left"]}]
        :middle -> cmds ++ [{:set_textAlign, ["center"]}]
        :end -> cmds ++ [{:set_textAlign, ["right"]}]
        _ -> cmds
      end

    cmds =
      case style[:fill] do
        nil -> cmds
        :none -> cmds
        :current_color -> cmds ++ [{:set_fillStyle, ["currentColor"]}]
        %Paint{} = paint -> cmds ++ [{:set_fillStyle, [Paint.first_color(paint)]}]
        color -> cmds ++ [{:set_fillStyle, [to_string(color)]}]
      end

    cmds
  end
end
