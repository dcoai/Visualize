defmodule Mix.Tasks.Vis.Surface do
  @shortdoc "Cross-reference spec/ against lib/ and render API_SURFACE.md (spec/12 §2)"

  @moduledoc """
  Cross-references every function `spec/` declares against every public function `lib/`
  defines, and renders the result to `API_SURFACE.md`.

      mix vis.surface            # print the two backlogs
      mix vis.surface --write    # regenerate API_SURFACE.md
      mix vis.surface --check    # fail if the golden has drifted from spec/ and lib/

  `--check` is HARD and fails on two things (spec/12 §2): the golden differing from what
  `spec/` and `lib/` render to — it is generated, so a difference means it was hand-edited,
  or the code or the spec changed without a regenerate — and any row whose status is not
  `specified`, which is how a public function nobody declared is caught. The byte
  comparison alone cannot catch that one: the golden is regenerated by the very change that
  introduces the undeclared function, so the file on disk agrees with itself.

  Bare `mix vis.surface` reports the same two backlogs without failing, and is the form to
  run while the work is in hand.
  """

  use Mix.Task

  alias Visualize.Audit

  @golden "API_SURFACE.md"
  @switches [write: :boolean, check: :boolean]

  @impl Mix.Task
  def run(argv) do
    {opts, _, _} = OptionParser.parse(argv, strict: @switches)

    root = File.cwd!()
    result = Audit.run(root)
    rendered = Audit.render(result)
    path = Path.join(root, @golden)

    cond do
      opts[:write] ->
        File.write!(path, rendered)
        Mix.shell().info("wrote #{path}")

      opts[:check] ->
        check!(path, rendered, result)

      true ->
        report(result)
    end
  end

  # Public so every failure branch is testable without re-scanning the tree.
  @doc false
  def check!(path, rendered, result) do
    # Drift first: a stale file makes any statement about its rows an answer about the
    # wrong document.
    drift!(path, rendered)
    specified!(result)
    Mix.shell().info("#{@golden} is current · every row specified")
  end

  defp drift!(path, rendered) do
    case File.read(path) do
      {:ok, ^rendered} ->
        :ok

      {:ok, _stale} ->
        Mix.raise(
          "#{@golden} has drifted from spec/ and lib/. Regenerate: mix vis.surface --write"
        )

      {:error, :enoent} ->
        Mix.raise("#{@golden} is missing. Generate it: mix vis.surface --write")
    end
  end

  defp specified!(%{unspecified: [], unimplemented: []}), do: :ok

  defp specified!(result) do
    count = length(result.unspecified) + length(result.unimplemented)

    Mix.raise(
      "#{@golden} has #{count} row(s) that are not `specified` (spec/12 §2).\n" <>
        backlog(
          "unspecified — defined in lib/, declared nowhere. Write the row in spec/",
          result.unspecified
        ) <>
        backlog(
          "unimplemented — declared in spec/, not defined in lib/. Build it, or delete " <>
            "the row",
          result.unimplemented
        ) <> "\nThen regenerate: mix vis.surface --write"
    )
  end

  defp backlog(_label, []), do: ""

  defp backlog(label, items) do
    "\n#{label}:\n" <> Enum.map_join(items, "\n", &"  #{&1}") <> "\n"
  end

  defp report(result) do
    shell = Mix.shell()
    shell.info("#{length(result.rows)} public functions · specified #{result.specified}")
    section(shell, "unspecified (defined in lib/, declared nowhere)", result.unspecified)
    section(shell, "unimplemented (declared in spec/, not defined)", result.unimplemented)
  end

  defp section(shell, label, []), do: shell.info("#{label}: none")

  defp section(shell, label, items) do
    shell.info("#{label} (#{length(items)}):")
    Enum.each(items, &shell.info("  #{&1}"))
  end
end
