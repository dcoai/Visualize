// The d3-geo reference oracle for Visualize.Geo.Clip (spec/07 §2.2, #509): a one-off
// generator, kept beside the golden it writes so the golden can be regenerated. It is the
// only JavaScript in the suite and runs only by hand; the test reads its output and never
// runs node. Tooling is Elixir by rule, and this is the exception the rule allows: d3-geo
// itself is the reference.
//
//   NODE_PATH=<dir with node_modules/d3-geo> node test/support/geo/clip_golden.mjs \
//     <ne_110m_land.geojson> > test/support/geo/clip_golden.jsonl
//
// Each case is one JSON line: the projection in the library's terms (`rotate` is the
// library's {lambda, phi, gamma}, the opposite sign of d3's, D-44), the input geometry,
// and d3's output stream, one entry per lineStart…lineEnd — "ring" inside a polygon,
// "line" otherwise — with every projection at precision(0), so no resampling: the points
// are exactly what the clip emitted, projected.
//
// `frame: "clip"` cases are taken through an equirectangular at scale 180/π and translate
// [0, 0], so x is the clipped longitude and −y the clipped latitude in degrees: the clip
// stream's own output.

import {createRequire} from "node:module";
import {readFileSync} from "node:fs";

const require = createRequire(import.meta.url);
const d3 = require("d3-geo");
const version = JSON.parse(readFileSync(new URL("../package.json", "file://" + require.resolve("d3-geo")), "utf8")).version;

const land = JSON.parse(readFileSync(process.argv[2], "utf8")).features;

function record(projection, object) {
  const out = [];
  let polygon = false, line = null;
  const sink = {
    point(x, y) { line.push([+x.toPrecision(15), +y.toPrecision(15)]); },
    lineStart() { line = []; },
    lineEnd() { out.push({kind: polygon ? "ring" : "line", points: line}); line = null; },
    polygonStart() { polygon = true; },
    polygonEnd() { polygon = false; },
    sphere() {}
  };
  d3.geoStream(object, projection.stream(sink));
  return out;
}

const types = {equirectangular: d3.geoEquirectangular, natural_earth: d3.geoNaturalEarth1};

function emit(name, p, geometry) {
  const projection = types[p.type]()
    .scale(p.scale).translate(p.translate)
    .rotate([-p.rotate[0], 0, 0])
    .precision(0);
  console.log(JSON.stringify({name, projection: p, geometry, output: record(projection, geometry)}));
}

const clipFrame = {type: "equirectangular", scale: 180 / Math.PI, translate: [0, 0], rotate: [0, 0, 0]};
const line = (coordinates) => ({type: "LineString", coordinates});
const polygon = (...rings) => ({type: "Polygon", coordinates: rings});
const around = (lat, lons) => lons.map((lon) => [lon, lat]).concat([[lons[0], lat]]);

console.log(`# Visualize.Geo.Clip conformance (#509): d3-geo ${version}'s own output, one case per line.`);
console.log("# Generated by test/support/geo/clip_golden.mjs (see its header for the command), from");
console.log("# Natural Earth 1:110m land (ne_110m_land v5.1.2, examples/priv/geo/) features 7, 21, 95, 112.");

const frameCases = {
  line_crosses_the_seam: line([[170, 10], [-170, 20], [-160, 30]]),
  line_crosses_it_three_times: line([[150, 0], [-150, 10], [150, 20], [-150, 30]]),
  line_with_a_vertex_on_the_seam: line([[170, 0], [180, 10], [-170, 20]]),
  line_over_a_pole: line([[0, 80], [180, 80], [170, 60]]),
  line_clear_of_the_seam: line([[-10, 0], [10, 10], [20, 0]]),
  polygon_across_the_seam: polygon([[170, 10], [170, 20], [-170, 20], [-170, 10], [170, 10]]),
  polygon_with_a_hole_across_it: polygon(
    [[160, -20], [160, 20], [-160, 20], [-160, -20], [160, -20]],
    [[175, -5], [-175, -5], [-175, 5], [175, 5], [175, -5]]
  ),
  polygon_clear_of_the_seam: polygon([[0, 0], [0, 10], [10, 10], [10, 0], [0, 0]]),
  polygon_around_the_north_pole: polygon(around(70, [-135, 135, 45, -45])),
  polygon_around_all_but_the_north_pole: polygon(around(70, [-135, -45, 45, 135])),
  polygon_around_the_south_pole: polygon(around(-70, [-135, -45, 45, 135])),
  antarctica_drawn_to_the_seam: polygon([
    [-180, -62], [-120, -74], [-60, -78], [0, -78], [60, -74], [120, -66], [180, -62],
    [180, -90], [-180, -90], [-180, -62]
  ]),
  multipolygon_across_the_seam: {type: "MultiPolygon", coordinates: [
    [[[170, 10], [170, 20], [-170, 20], [-170, 10], [170, 10]]],
    [[[175, -40], [175, -30], [-175, -30], [-175, -40], [175, -40]]]
  ]}
};

for (const [name, geometry] of Object.entries(frameCases)) emit(name, clipFrame, geometry);

const pick = (i) => land[i].geometry;
const projected = [
  ["equirectangular", 90, [7, 95, 21]],
  ["natural_earth", 90, [7, 95]],
  ["natural_earth", -150, [7, 112]]
];

for (const [type, lambda, features] of projected) {
  for (const i of features) {
    emit(`${type}_rotated_${lambda}_land_${i}`,
      {type, scale: 100, translate: [480, 250], rotate: [lambda, 0, 0]}, pick(i));
  }
}
