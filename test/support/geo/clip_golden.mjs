// The d3-geo reference oracle for Visualize.Geo.Clip and the projection's rotation
// (spec/07 §1.4, §2.2, #509, #510, #511): a one-off generator, kept beside the golden it
// writes so the golden can be regenerated. It is the only JavaScript in the suite and runs
// only by hand; the test reads its output and never runs node. Tooling is Elixir by rule,
// and this is the exception the rule allows: d3-geo itself is the reference.
//
//   NODE_PATH=<dir with node_modules/d3-geo> node test/support/geo/clip_golden.mjs \
//     <ne_110m_land.geojson> > test/support/geo/clip_golden.jsonl
//
// Each case is one JSON line: the projection in the library's terms (`rotate` is the
// library's {lambda, phi, gamma}, which is d3's [-lambda, phi, gamma]: `phi` and `gamma`
// are d3's own and only `lambda` keeps the library's opposite sign, spec/07 §1.4, D-44,
// D-129), the input geometry, and d3's output stream, one entry per lineStart…lineEnd —
// "ring" inside a polygon, "line" otherwise — with every projection at precision(0), so
// no resampling: the points are exactly what the clip emitted, projected. A rotation case
// (#511) has `points` in place of the geometry, and d3's `projected` and `inverted` points.
//
// `frame: "clip"` cases are taken through an equirectangular at scale 180/π and translate
// [0, 0], so x is the clipped longitude and −y the clipped latitude in degrees: the clip
// stream's own output. A projection's `clip_angle`, where a case gives one, is d3's
// `clipAngle`; without one each type keeps d3's default, which the library's `new/1`
// matches (spec/07 §1.5) — the orthographic's 90 + 1e-6, the whole-sphere azimuthals'
// 180 - 1e-3 — so those cases hold the defaults to d3's as well.

