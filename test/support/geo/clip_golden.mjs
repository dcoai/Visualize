// The rotation itself (#511, D-129): points projected under several [lambda, phi, gamma]
// — d3's projected point where its stream emits the point and null where its clip drops
// it — and d3's inverse of each projected point.
function project(p, points) {
  const projection = d3Projection(p);
  const precise = (xy) => xy && [+xy[0].toPrecision(17), +xy[1].toPrecision(17)];
  const projected = points.map((point) => {
    let seen = null;
    d3.geoStream({type: "Point", coordinates: point}, projection.stream({
      point(x, y) { seen = [x, y]; }, lineStart() {}, lineEnd() {},
      polygonStart() {}, polygonEnd() {}, sphere() {}
    }));
    return precise(seen);
  });
  const inverted = projected.map((xy) => xy && precise(projection.invert(xy)));
  return {projected, inverted};
}

