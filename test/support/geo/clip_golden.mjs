function record(projection, object) {
  const out = [];
  let polygon = false, line = null;
  const sink = {
    point(x, y) { line.push([+x.toPrecision(15), +y.toPrecision(15)]); },
    lineStart() { line = []; },
    lineEnd() { out.push({kind: polygon ? "ring" : "line", points: line}); line = null; },
    polygonStart() { polygon = true; },
    polygonEnd() { polygon = false; },
    sphere() {}
  };
  d3.geoStream(object, projection.stream(sink));
  return out;
}

const types = {
  equirectangular: d3.geoEquirectangular,
  mercator: d3.geoMercator,
  natural_earth: d3.geoNaturalEarth1,
  equal_earth: d3.geoEqualEarth,
  orthographic: d3.geoOrthographic,
  stereographic: d3.geoStereographic,
  azimuthal_equal_area: d3.geoAzimuthalEqualArea,
  azimuthal_equidistant: d3.geoAzimuthalEquidistant,
  gnomonic: d3.geoGnomonic
};

function d3Projection(p) {
  const projection = types[p.type]()
    .scale(p.scale).translate(p.translate)
    .rotate([-p.rotate[0], p.rotate[1], p.rotate[2]])
    .precision(0);
  if (p.clip_angle !== undefined) projection.clipAngle(p.clip_angle);
  return projection;
}

function emit(name, p, geometry) {
  console.log(JSON.stringify({name, projection: p, geometry, output: record(d3Projection(p), geometry)}));
}

