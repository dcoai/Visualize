// The d3-geo reference oracle for Visualize.Geo.Circle (spec/07 §2.5, #525, D-131): a
// one-off generator, kept beside the golden it writes so the golden can be regenerated, as
// clip_golden.mjs is beside its own. It runs only by hand; the test reads its output and
// never runs node. Tooling is Elixir by rule, and this is the exception the rule allows:
// d3-geo itself is the reference.
//
//   NODE_PATH=<dir with node_modules/d3-geo> node test/support/geo/circle_golden.mjs \
//     > test/support/geo/circle_golden.jsonl
//
// Each case is one JSON line: the circle's `center`, `radius` and `precision`, in degrees,
// and the `ring` d3-geo's `geoCircle` returns for them, every number as JSON.stringify
// writes it (the shortest that reads back as the same double), so the test can hold the
// port to 1e-9 and closer.

import {createRequire} from "node:module";
import {readFileSync} from "node:fs";

const require = createRequire(import.meta.url);
const d3 = require("d3-geo");
const version = JSON.parse(readFileSync(new URL("../package.json", "file://" + require.resolve("d3-geo")), "utf8")).version;

console.log(`# Visualize.Geo.Circle conformance (#525): d3-geo ${version}'s geoCircle, one case per line.`);
console.log("# Generated by test/support/geo/circle_golden.mjs (see its header for the command).");

const centers = [
  [0, 0], [10, 20], [-120, 45], [170, -30], [-180, 10], [0, 90], [0, -90], [45, -89.5],
  [200, 30], [-75.5, -23.44]
];
const radii = [0, 1, 30, 90, 120, 179, 200, -30];
const precisions = [6, 7, 45, 0];

// Every centre and radius at the default precision of 6°, one that does not divide 360°, a
// coarse one and 0; and d3-geo 3.1.1's own default of 2° and a fine 0.5° on a few.
const cases = [];
for (const center of centers) {
  for (const radius of radii) {
    for (const precision of precisions) cases.push([center, radius, precision]);
  }
}
for (const center of [[10, 20], [-120, 45], [0, 90]]) {
  for (const radius of [30, 90, 150]) {
    for (const precision of [2, 0.5]) cases.push([center, radius, precision]);
  }
}

for (const [center, radius, precision] of cases) {
  const ring = d3.geoCircle().center(center).radius(radius).precision(precision)().coordinates[0];
  console.log(JSON.stringify({center, radius, precision, ring}));
}
